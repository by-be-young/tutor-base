-- 课件托管 P1 消息提醒（幂等版，供已对齐的线上库重复执行）
-- 与 V22__courseware_notification.sql 等价。

CREATE TABLE IF NOT EXISTS public.course_notification (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    kind text NOT NULL,
    title text NOT NULL,
    body text NOT NULL DEFAULT '',
    source_teacher_account_id bigint,
    copy_id bigint,
    share_id bigint,
    article_id bigint,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    read_at timestamp with time zone,
    CONSTRAINT course_notification_kind_check
        CHECK (kind IN ('share_acquired', 'source_updated', 'share_revoked'))
);

CREATE INDEX IF NOT EXISTS course_notification_recipient_idx
    ON public.course_notification (recipient_account_id, created_at DESC);

CREATE INDEX IF NOT EXISTS course_notification_unread_idx
    ON public.course_notification (recipient_account_id)
    WHERE read_at IS NULL;

ALTER TABLE public.course_notification ENABLE ROW LEVEL SECURITY;

DO $v22_runtime$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        RETURN;
    END IF;

    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.course_notification TO tutor_base_runtime;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policy
        WHERE polrelid = 'public.course_notification'::regclass
          AND polname = 'tutor_base_runtime_course_notification_all'
    ) THEN
        CREATE POLICY tutor_base_runtime_course_notification_all
            ON public.course_notification FOR ALL TO tutor_base_runtime
            USING (true) WITH CHECK (true);
    END IF;

    IF to_regclass('public.course_notification_id_seq') IS NOT NULL THEN
        GRANT USAGE ON SEQUENCE public.course_notification_id_seq TO tutor_base_runtime;
    END IF;
END
$v22_runtime$;
