ALTER TABLE public.course_template ENABLE ROW LEVEL SECURITY;

DO $v24_runtime$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        RETURN;
    END IF;

    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.course_template TO tutor_base_runtime;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policy
        WHERE polrelid = 'public.course_template'::regclass
          AND polname = 'tutor_base_runtime_course_template_all'
    ) THEN
        CREATE POLICY tutor_base_runtime_course_template_all
            ON public.course_template FOR ALL TO tutor_base_runtime
            USING (true) WITH CHECK (true);
    END IF;

    IF to_regclass('public.course_template_id_seq') IS NOT NULL THEN
        GRANT USAGE ON SEQUENCE public.course_template_id_seq TO tutor_base_runtime;
    END IF;
END
$v24_runtime$;
