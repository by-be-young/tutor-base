-- 课件托管 P2：模板库（新建课件时的骨架来源）
--
-- 设计稿原本把模板放在仓库 `templates/<科目>/<类型>.md`，运行时后端读不到仓库文件，
-- 因此落到库里：`subject IS NULL` 表示全科通用模板。

CREATE TABLE IF NOT EXISTS public.course_template (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject text,
    kind text NOT NULL,
    name text NOT NULL,
    markdown text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT course_template_kind_check
        CHECK (kind IN ('new_lesson', 'practice', 'review', 'topic'))
);

CREATE UNIQUE INDEX IF NOT EXISTS course_template_unique
    ON public.course_template (coalesce(subject, '*'), kind, name);

