-- 手工对齐脚本：教师注册审核（V17）与超级管理员标记。
-- 用于生产库已手工变更、Flyway 历史尚未记账的场景；可重复执行，结果与 V17 一致。

SET lock_timeout = '5s';
SET statement_timeout = '30s';

ALTER TABLE public.account
    ADD COLUMN IF NOT EXISTS is_super_admin boolean NOT NULL DEFAULT false;

DO $teacher_review_constraint$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.account'::regclass
          AND conname = 'account_super_admin_role_check'
    ) THEN
        ALTER TABLE public.account
            ADD CONSTRAINT account_super_admin_role_check
                CHECK (NOT is_super_admin OR role = 'administrator');
    END IF;
END
$teacher_review_constraint$;

UPDATE public.account
SET is_super_admin = true
WHERE username_normalized = 'young'
  AND role = 'administrator';

CREATE TABLE IF NOT EXISTS public.teacher_registration_application (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    username_normalized text NOT NULL,
    password_hash text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    rejection_reason text,
    reviewed_by bigint REFERENCES public.account (id) ON DELETE SET NULL,
    reviewed_at timestamp with time zone,
    approved_account_id bigint REFERENCES public.account (id) ON DELETE RESTRICT,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT teacher_registration_application_username_trimmed_check
        CHECK (username = btrim(username)),
    CONSTRAINT teacher_registration_application_username_normalized_check
        CHECK (username_normalized = lower(btrim(username))),
    CONSTRAINT teacher_registration_application_status_check
        CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT teacher_registration_application_reason_length_check
        CHECK (rejection_reason IS NULL OR char_length(rejection_reason) <= 500),
    CONSTRAINT teacher_registration_application_state_check CHECK (
        (status = 'pending'
            AND reviewed_by IS NULL
            AND reviewed_at IS NULL
            AND rejection_reason IS NULL
            AND approved_account_id IS NULL)
        OR (status = 'approved'
            AND reviewed_at IS NOT NULL
            AND rejection_reason IS NULL
            AND approved_account_id IS NOT NULL)
        OR (status = 'rejected'
            AND reviewed_at IS NOT NULL
            AND rejection_reason IS NOT NULL
            AND btrim(rejection_reason) <> ''
            AND approved_account_id IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS teacher_registration_application_pending_username
    ON public.teacher_registration_application (username_normalized)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS teacher_registration_application_status_created_idx
    ON public.teacher_registration_application (status, created_at DESC);

CREATE INDEX IF NOT EXISTS teacher_registration_application_reviewed_by_idx
    ON public.teacher_registration_application (reviewed_by);

ALTER TABLE public.teacher_registration_application ENABLE ROW LEVEL SECURITY;

DO $teacher_review_runtime$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON TABLE public.teacher_registration_application TO tutor_base_runtime';

        IF to_regclass('public.teacher_registration_application_id_seq') IS NOT NULL THEN
            EXECUTE 'GRANT USAGE ON SEQUENCE public.teacher_registration_application_id_seq TO tutor_base_runtime';
        END IF;

        IF NOT EXISTS (
            SELECT 1 FROM pg_policy
            WHERE polrelid = 'public.teacher_registration_application'::regclass
              AND polname = 'tutor_base_runtime_teacher_registration_application_all'
        ) THEN
            EXECUTE 'CREATE POLICY tutor_base_runtime_teacher_registration_application_all '
                || 'ON public.teacher_registration_application FOR ALL TO tutor_base_runtime '
                || 'USING (true) WITH CHECK (true)';
        END IF;
    END IF;
END
$teacher_review_runtime$;
