-- ============================================================================
-- 补齐在 Supabase 现有库中缺失的学习 / 奖励表
-- 背景：当前库只有 account / student / user_points / daily_check_in 等表，
--       V1 基线的三张学习表和 V5 的两张奖励表尚未创建，导致后端
--       /wrong-book、/rewards、/articles/study-progress 返回 503。
-- 特性：可重复执行（IF NOT EXISTS + 约束/触发器存在性判断），不修改已有数据。
-- ============================================================================

BEGIN;

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

-- ---------------------------------------------------------------------------
-- V1 学习基线：标准答案 / 作答 / 错题
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.article_answer_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blog_id bigint NOT NULL,
    answer_text text DEFAULT ''::text NOT NULL,
    auto_grade boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    question_id text NOT NULL,
    CONSTRAINT article_answer_keys_blog_question_unique UNIQUE (blog_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_article_answer_keys_blog_id
    ON public.article_answer_keys (blog_id);
CREATE INDEX IF NOT EXISTS idx_article_answer_keys_question_id
    ON public.article_answer_keys (question_id);

CREATE TABLE IF NOT EXISTS public.article_question_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blog_id bigint NOT NULL,
    student_id bigint NOT NULL,
    answer_text text DEFAULT ''::text NOT NULL,
    review_status text DEFAULT 'pending'::text NOT NULL,
    review_result text,
    submitted_at timestamp with time zone DEFAULT now() NOT NULL,
    reviewed_at timestamp with time zone,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    question_id text NOT NULL,
    CONSTRAINT article_question_submissions_review_status_check
        CHECK (review_status = ANY (ARRAY['pending'::text, 'reviewed'::text])),
    CONSTRAINT article_question_submissions_review_result_check
        CHECK (review_result = ANY (ARRAY['correct'::text, 'partial'::text, 'wrong'::text])),
    CONSTRAINT article_question_submissions_blog_student_question_unique
        UNIQUE (blog_id, student_id, question_id),
    CONSTRAINT article_question_submissions_review_state_check
        CHECK (
            (review_status = 'pending' AND review_result IS NULL AND reviewed_at IS NULL)
            OR
            (review_status = 'reviewed' AND review_result IS NOT NULL AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT article_question_submissions_student_id_fkey
        FOREIGN KEY (student_id) REFERENCES public.student (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_article_question_submissions_blog_student
    ON public.article_question_submissions (blog_id, student_id);
CREATE INDEX IF NOT EXISTS idx_article_question_submissions_question_id
    ON public.article_question_submissions (question_id);
CREATE INDEX IF NOT EXISTS idx_article_question_submissions_review_status
    ON public.article_question_submissions (review_status);

CREATE TABLE IF NOT EXISTS public.wrong_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL,
    correct_answer text DEFAULT ''::text NOT NULL,
    my_answer text DEFAULT ''::text NOT NULL,
    wrong_reason text DEFAULT ''::text NOT NULL,
    tags text[] DEFAULT '{}'::text[] NOT NULL,
    note text DEFAULT ''::text NOT NULL,
    source_blog_id bigint,
    source_question_id text,
    is_manual boolean DEFAULT true NOT NULL,
    mastered boolean DEFAULT false NOT NULL,
    removed boolean DEFAULT false NOT NULL,
    wrong_count integer DEFAULT 1 NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT wrong_questions_student_source_unique
        UNIQUE (student_id, source_blog_id, source_question_id),
    CONSTRAINT wrong_questions_student_id_fkey
        FOREIGN KEY (student_id) REFERENCES public.student (id) ON DELETE CASCADE,
    CONSTRAINT wrong_questions_wrong_count_check CHECK (wrong_count >= 1)
);

-- ---------------------------------------------------------------------------
-- V5 奖励：里程碑领取记录 / 收藏卡
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.task_claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL,
    task_id bigint NOT NULL,
    claimed_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT task_claims_student_task_unique UNIQUE (student_id, task_id),
    CONSTRAINT task_claims_student_id_fkey
        FOREIGN KEY (student_id) REFERENCES public.student (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.card_collection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL,
    milestone_points bigint NOT NULL,
    card_key text NOT NULL,
    set_key text NOT NULL,
    rarity text NOT NULL,
    claimed_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT card_collection_milestone_positive CHECK (milestone_points > 0),
    CONSTRAINT card_collection_rarity_check CHECK (rarity IN ('common', 'rare')),
    CONSTRAINT card_collection_student_milestone_unique UNIQUE (student_id, milestone_points),
    CONSTRAINT card_collection_student_id_fkey
        FOREIGN KEY (student_id) REFERENCES public.student (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS task_claims_student_id_idx
    ON public.task_claims (student_id);
CREATE INDEX IF NOT EXISTS card_collection_student_id_idx
    ON public.card_collection (student_id);

-- ---------------------------------------------------------------------------
-- updated_at 触发器（V2）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$function$;

DO $triggers$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.article_answer_keys'::regclass
          AND tgname = 'article_answer_keys_set_updated_at'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER article_answer_keys_set_updated_at
            BEFORE UPDATE ON public.article_answer_keys
            FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.article_question_submissions'::regclass
          AND tgname = 'article_question_submissions_set_updated_at'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER article_question_submissions_set_updated_at
            BEFORE UPDATE ON public.article_question_submissions
            FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.wrong_questions'::regclass
          AND tgname = 'wrong_questions_set_updated_at'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER wrong_questions_set_updated_at
            BEFORE UPDATE ON public.wrong_questions
            FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
    END IF;
END
$triggers$;

-- student.permissions 非空约束（存在空值则跳过，保持可重复执行）
DO $student_permissions$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.student WHERE permissions IS NULL) THEN
        ALTER TABLE public.student ALTER COLUMN permissions SET NOT NULL;
    END IF;
END
$student_permissions$;

COMMIT;
