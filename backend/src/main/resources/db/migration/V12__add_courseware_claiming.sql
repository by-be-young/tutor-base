-- 多管理员下的课件认领：管理员可以认领学科（自动覆盖该学科当前及未来全部课件），
-- 也可以对单篇课件单独认领。学科与管理员是多对多关系，不独占。
--
-- 本脚本必须是幂等的：数据库可能已经通过 database/reconciliation/2026-10-29_courseware_claiming.sql
-- 手工对齐过这些对象，但 Flyway 历史表尚未记账。全新数据库执行结果与 reconciliation 完全一致。
-- RLS policy 只在运行时角色已存在时创建：空 PostgreSQL 上 Flyway 先于 provision_runtime_role.sql
-- 执行，角色不存在时跳过，由 provision 脚本补建；Supabase 等已 provision 的库会在迁移时直接建好。

SET lock_timeout = '5s';
SET statement_timeout = '30s';

-- 课件目录：article_id 是前端 articles.json 中的稳定课件 ID。
CREATE TABLE IF NOT EXISTS public.courseware_catalog (
    article_id bigint PRIMARY KEY,
    subject text NOT NULL,
    title text,
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS courseware_catalog_subject_idx
    ON public.courseware_catalog (subject);

-- 学科认领：一名管理员可认领多个学科，同一学科也可被多名管理员认领。
CREATE TABLE IF NOT EXISTS public.admin_subject_claim (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    subject text NOT NULL,
    claimed_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT admin_subject_claim_admin_subject_unique UNIQUE (admin_account_id, subject)
);

CREATE INDEX IF NOT EXISTS admin_subject_claim_subject_idx
    ON public.admin_subject_claim (subject);

-- 单篇课件认领：独立于学科认领存在，释放学科认领后仍然保留。
CREATE TABLE IF NOT EXISTS public.admin_courseware_claim (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    article_id bigint NOT NULL REFERENCES public.courseware_catalog (article_id) ON DELETE CASCADE,
    claimed_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT admin_courseware_claim_admin_article_unique UNIQUE (admin_account_id, article_id)
);

CREATE INDEX IF NOT EXISTS admin_courseware_claim_article_idx
    ON public.admin_courseware_claim (article_id);

ALTER TABLE public.courseware_catalog ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_subject_claim ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_courseware_claim ENABLE ROW LEVEL SECURITY;

-- 运行时角色由 database/operations/provision_runtime_role.sql 创建；空库上迁移时角色尚不存在，
-- 因此仅在角色存在时创建 policy，避免 migration 因缺少 role 失败。
DO $v12_policies$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        IF NOT EXISTS (
            SELECT 1 FROM pg_policy
            WHERE polrelid = 'public.courseware_catalog'::regclass
              AND polname = 'tutor_base_runtime_courseware_catalog_all'
        ) THEN
            CREATE POLICY tutor_base_runtime_courseware_catalog_all
                ON public.courseware_catalog
                FOR ALL TO tutor_base_runtime USING (true) WITH CHECK (true);
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM pg_policy
            WHERE polrelid = 'public.admin_subject_claim'::regclass
              AND polname = 'tutor_base_runtime_admin_subject_claim_all'
        ) THEN
            CREATE POLICY tutor_base_runtime_admin_subject_claim_all
                ON public.admin_subject_claim
                FOR ALL TO tutor_base_runtime USING (true) WITH CHECK (true);
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM pg_policy
            WHERE polrelid = 'public.admin_courseware_claim'::regclass
              AND polname = 'tutor_base_runtime_admin_courseware_claim_all'
        ) THEN
            CREATE POLICY tutor_base_runtime_admin_courseware_claim_all
                ON public.admin_courseware_claim
                FOR ALL TO tutor_base_runtime USING (true) WITH CHECK (true);
        END IF;
    END IF;
END
$v12_policies$;
