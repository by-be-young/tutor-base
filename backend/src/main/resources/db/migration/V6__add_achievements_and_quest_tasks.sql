-- 成就系统与周期/限时任务
-- 成就：分层等级，领取时由服务端发放积分
-- 任务：每日/每周自动刷新 + 限时任务（接取后进入宽限截止时间）

CREATE TABLE IF NOT EXISTS public.achievement_claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.student (id) ON DELETE CASCADE,
    achievement_key text NOT NULL,
    tier_level integer NOT NULL CHECK (tier_level > 0),
    reward_points bigint NOT NULL CHECK (reward_points > 0),
    claimed_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT achievement_claims_unique UNIQUE (student_id, achievement_key, tier_level)
);

CREATE INDEX IF NOT EXISTS achievement_claims_student_idx
    ON public.achievement_claims (student_id);

CREATE TABLE IF NOT EXISTS public.task_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.student (id) ON DELETE CASCADE,
    task_key text NOT NULL,
    accepted_at timestamp with time zone NOT NULL DEFAULT now(),
    deadline_at timestamp with time zone NOT NULL,
    claimed_at timestamp with time zone,
    CONSTRAINT task_assignments_unique UNIQUE (student_id, task_key)
);

CREATE INDEX IF NOT EXISTS task_assignments_student_idx
    ON public.task_assignments (student_id);

-- 复用 V5 的 task_claims 记录周期/限时任务领取；旧 task_id 允许为空
ALTER TABLE public.task_claims ALTER COLUMN task_id DROP NOT NULL;
ALTER TABLE public.task_claims ADD COLUMN IF NOT EXISTS task_key text;
ALTER TABLE public.task_claims ADD COLUMN IF NOT EXISTS period_key text;
ALTER TABLE public.task_claims ADD COLUMN IF NOT EXISTS reward_points bigint NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS task_claims_period_unique
    ON public.task_claims (student_id, task_key, period_key)
    WHERE task_key IS NOT NULL;
