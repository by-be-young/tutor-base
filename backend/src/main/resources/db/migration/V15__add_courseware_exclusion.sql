-- 学科覆盖下的单篇课件排除：管理员认领整个学科后，仍可把其中若干篇从“我的课件”释放。
--
-- 可见范围重新定义为：
--   (学科已认领 且 该篇未被该管理员排除) 或 (该篇被该管理员单独认领)
-- 释放单篇时写入排除行；再次单篇认领或重新认领整个学科时删除排除行。
--
-- 本脚本必须幂等：对象可能已通过 database/reconciliation/2026-10-30_courseware_exclusion.sql
-- 手工建好但 Flyway 尚未记账。运行时角色在空数据库上可能尚不存在（provision 脚本后执行），
-- 此时跳过授权与 policy，由 provision 脚本补建；已 provision 的库在迁移时直接补齐。

SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.admin_courseware_exclusion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    article_id bigint NOT NULL REFERENCES public.courseware_catalog (article_id) ON DELETE CASCADE,
    excluded_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT admin_courseware_exclusion_admin_article_unique UNIQUE (admin_account_id, article_id)
);

CREATE INDEX IF NOT EXISTS admin_courseware_exclusion_article_idx
    ON public.admin_courseware_exclusion (article_id);

ALTER TABLE public.admin_courseware_exclusion ENABLE ROW LEVEL SECURITY;

DO $v15_runtime$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        RETURN;
    END IF;

    EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.admin_courseware_exclusion TO tutor_base_runtime';

    IF to_regclass('public.admin_courseware_exclusion_id_seq') IS NOT NULL THEN
        EXECUTE 'GRANT USAGE ON SEQUENCE public.admin_courseware_exclusion_id_seq TO tutor_base_runtime';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policy
        WHERE polrelid = 'public.admin_courseware_exclusion'::regclass
          AND polname = 'tutor_base_runtime_admin_courseware_exclusion_all'
    ) THEN
        EXECUTE 'CREATE POLICY tutor_base_runtime_admin_courseware_exclusion_all ON public.admin_courseware_exclusion FOR ALL TO tutor_base_runtime USING (true) WITH CHECK (true)';
    END IF;
END
$v15_runtime$;
