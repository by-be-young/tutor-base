DO $v21_runtime$
DECLARE
    target text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tutor_base_runtime') THEN
        RETURN;
    END IF;

    FOREACH target IN ARRAY ARRAY[
        'student_teacher', 'course_release', 'course_release_head', 'course_article',
        'course_share', 'course_copy', 'course_subscription', 'course_draft',
        'course_asset_ref', 'course_operation_log'
    ] LOOP
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO tutor_base_runtime', target);
        IF NOT EXISTS (
            SELECT 1 FROM pg_policy
            WHERE polrelid = format('public.%I', target)::regclass
              AND polname = 'tutor_base_runtime_' || target || '_all'
        ) THEN
            EXECUTE format(
                'CREATE POLICY %I ON public.%I FOR ALL TO tutor_base_runtime USING (true) WITH CHECK (true)',
                'tutor_base_runtime_' || target || '_all', target
            );
        END IF;
    END LOOP;

    FOREACH target IN ARRAY ARRAY[
        'course_release', 'course_article', 'course_share', 'course_copy',
        'course_subscription', 'course_operation_log'
    ] LOOP
        IF to_regclass(format('public.%I_id_seq', target)) IS NOT NULL THEN
            EXECUTE format('GRANT USAGE ON SEQUENCE public.%I_id_seq TO tutor_base_runtime', target);
        END IF;
    END LOOP;
END
$v21_runtime$;

