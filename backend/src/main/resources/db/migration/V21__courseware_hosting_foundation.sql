-- 课件托管化（P0 基础设施）：老师命名空间、不可变发布版本、复制/分享关系与学习记录快照。
--
-- 本脚本只做「加表 + 加列 + 回填」，不改动任何现有主键/唯一键，
-- 保证旧代码（按全局 article_id、blog_id 读写）在迁移后照常运行；
-- 换主键与唯一键调整放到后续版本（V22+），与代码切换同批上线。
--
-- 本脚本必须是幂等的：database/reconciliation/2026-11-01_courseware_hosting.sql 可手工重复执行。
--
-- 关键不变量：
--   I1 article_id 在老师命名空间内稳定（(teacher_account_id, article_id) 语义唯一，逻辑路径可改）
--   I2 发布不可变：course_release 一行 = 一个版本，manifest 按版本独立存放
--   I3 学习记录保存当时的题干/答案快照
--   I4 跨老师内容流动只能显式发生（course_share / course_copy）

SET lock_timeout = '5s';
SET statement_timeout = '30s';

-- ----------------------------------------------------------------------------
-- 0) 初始老师：当前唯一有课件的管理员。取最早创建的可用管理员账号，避免硬编码 ID。
--    空库（无管理员）时为 NULL，此时没有任何课件目录行需要回填。
-- ----------------------------------------------------------------------------
CREATE TEMP TABLE IF NOT EXISTS tmp_initial_teacher ON COMMIT DROP AS
SELECT COALESCE(
           (SELECT a.id FROM public.account AS a
             WHERE a.role = 'administrator' AND a.status = 'active'
             ORDER BY a.id LIMIT 1),
           (SELECT a.id FROM public.account AS a ORDER BY a.id LIMIT 1)
       ) AS teacher_account_id;

-- ----------------------------------------------------------------------------
-- 1) 学员 ↔ 老师：一名学员可同时属于多位老师；primary 仅用于首页默认分组
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.student_teacher (
    student_id bigint NOT NULL REFERENCES public.student (id) ON DELETE CASCADE,
    teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    is_primary boolean NOT NULL DEFAULT false,
    linked_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, teacher_account_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS student_teacher_single_primary_idx
    ON public.student_teacher (student_id)
    WHERE is_primary;
CREATE INDEX IF NOT EXISTS student_teacher_teacher_idx
    ON public.student_teacher (teacher_account_id);

-- 存量：student.claimed_by 即「主老师」，迁移为显式关联；claimed_by 之后只作默认值保留
INSERT INTO public.student_teacher (student_id, teacher_account_id, is_primary)
SELECT s.id, s.claimed_by, true
FROM public.student AS s
WHERE s.claimed_by IS NOT NULL
ON CONFLICT (student_id, teacher_account_id) DO UPDATE
    SET is_primary = public.student_teacher.is_primary OR EXCLUDED.is_primary;

-- ----------------------------------------------------------------------------
-- 2) 发布版本（不可变）
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.course_release (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    subject text NOT NULL,
    version integer NOT NULL,
    manifest_path text NOT NULL,
    manifest_hash text NOT NULL,
    published_at timestamp with time zone NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'published',
    CONSTRAINT course_release_status_check
        CHECK (status IN ('published', 'archived', 'revoked')),
    CONSTRAINT course_release_teacher_subject_version_unique
        UNIQUE (teacher_account_id, subject, version)
);

CREATE INDEX IF NOT EXISTS course_release_teacher_subject_idx
    ON public.course_release (teacher_account_id, subject, version DESC);

-- 当前生效版本指针
CREATE TABLE IF NOT EXISTS public.course_release_head (
    teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    subject text NOT NULL,
    release_id bigint NOT NULL REFERENCES public.course_release (id) ON DELETE CASCADE,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (teacher_account_id, subject)
);

-- 发布内的一篇课件（每个版本各存一份，保证历史可复现）
CREATE TABLE IF NOT EXISTS public.course_article (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES public.course_release (id) ON DELETE CASCADE,
    teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    article_id bigint NOT NULL,
    legacy_article_id bigint,
    subject text NOT NULL,
    title text NOT NULL,
    series text NOT NULL,
    logical_path text NOT NULL,
    content_hash text NOT NULL,
    answer_hash text NOT NULL,
    question_count integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT course_article_release_article_unique UNIQUE (release_id, article_id)
);

-- 同一老师同一 article_id 会在多个版本里重复出现，因此不能对 (teacher, article) 加唯一约束；
-- 该索引用于「按老师取某篇的当前版本」。
CREATE INDEX IF NOT EXISTS course_article_teacher_article_idx
    ON public.course_article (teacher_account_id, article_id, release_id DESC);
CREATE INDEX IF NOT EXISTS course_article_content_hash_idx
    ON public.course_article (content_hash);
CREATE INDEX IF NOT EXISTS course_article_teacher_path_idx
    ON public.course_article (teacher_account_id, logical_path);

-- ----------------------------------------------------------------------------
-- 3) 分享（主动分享才可见；整科动态跟随当前版本，单篇按 article_id）
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.course_share (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    scope_type text NOT NULL,
    subject text NOT NULL,
    article_id bigint,
    allow_preview boolean NOT NULL DEFAULT true,
    allow_copy boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    revoked_at timestamp with time zone,
    CONSTRAINT course_share_scope_type_check
        CHECK (scope_type IN ('subject', 'article')),
    CONSTRAINT course_share_article_requires_id
        CHECK ((scope_type = 'article' AND article_id IS NOT NULL)
            OR (scope_type = 'subject' AND article_id IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS course_share_subject_active_unique
    ON public.course_share (owner_teacher_account_id, subject)
    WHERE scope_type = 'subject' AND revoked_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS course_share_article_active_unique
    ON public.course_share (owner_teacher_account_id, subject, article_id)
    WHERE scope_type = 'article' AND revoked_at IS NULL;

-- ----------------------------------------------------------------------------
-- 4) 获取（复制/导入）关系与整科订阅
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.course_copy (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    local_article_id bigint NOT NULL,
    source_teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    source_article_id bigint NOT NULL,
    source_release_id bigint NOT NULL REFERENCES public.course_release (id),
    base_content_hash text NOT NULL,
    base_answer_hash text NOT NULL,
    source_logical_path text NOT NULL,
    local_logical_path text NOT NULL,
    local_title text NOT NULL,
    acquired_via text NOT NULL DEFAULT 'copy',
    acquired_at timestamp with time zone NOT NULL DEFAULT now(),
    dismissed_hash text,
    status text NOT NULL DEFAULT 'active',
    CONSTRAINT course_copy_acquired_via_check
        CHECK (acquired_via IN ('copy', 'import', 'download')),
    CONSTRAINT course_copy_status_check
        CHECK (status IN ('active', 'source_unavailable', 'source_revoked')),
    CONSTRAINT course_copy_local_unique UNIQUE (owner_account_id, local_article_id),
    CONSTRAINT course_copy_source_unique
        UNIQUE (owner_account_id, source_teacher_account_id, source_article_id)
);

CREATE INDEX IF NOT EXISTS course_copy_owner_idx
    ON public.course_copy (owner_account_id, status);

CREATE TABLE IF NOT EXISTS public.course_subscription (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    source_teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    source_subject text NOT NULL,
    base_release_id bigint NOT NULL REFERENCES public.course_release (id),
    local_root_path text NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'active',
    CONSTRAINT course_subscription_status_check
        CHECK (status IN ('active', 'source_unavailable', 'revoked')),
    CONSTRAINT course_subscription_unique
        UNIQUE (subscriber_account_id, source_teacher_account_id, source_subject)
);

-- ----------------------------------------------------------------------------
-- 5) 草稿（在线编辑器，不进入发布版本）
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.course_draft (
    teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    article_id bigint NOT NULL,
    markdown text NOT NULL,
    layout_map jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (teacher_account_id, article_id)
);

-- ----------------------------------------------------------------------------
-- 6) 资产引用计数与操作审计
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.course_asset_ref (
    asset_hash text NOT NULL,
    owner_teacher_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    article_id bigint NOT NULL,
    ref_count integer NOT NULL DEFAULT 1,
    PRIMARY KEY (asset_hash, owner_teacher_account_id, article_id)
);

CREATE TABLE IF NOT EXISTS public.course_operation_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id bigint NOT NULL REFERENCES public.account (id) ON DELETE CASCADE,
    action text NOT NULL,
    teacher_account_id bigint NOT NULL,
    article_id bigint,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT course_operation_log_action_check
        CHECK (action IN ('publish', 'copy', 'apply_update', 'dismiss_update', 'import', 'export',
                          'delete', 'share', 'revoke_share', 'rename', 'git_push'))
);

CREATE INDEX IF NOT EXISTS course_operation_log_teacher_idx
    ON public.course_operation_log (teacher_account_id, created_at DESC);

-- ----------------------------------------------------------------------------
-- 7) 既有表加列（可空，先回填，代码切换后再收紧）
-- ----------------------------------------------------------------------------
ALTER TABLE public.courseware_catalog
    ADD COLUMN IF NOT EXISTS teacher_account_id bigint,
    ADD COLUMN IF NOT EXISTS legacy_article_id bigint,
    ADD COLUMN IF NOT EXISTS content_hash text;

UPDATE public.courseware_catalog
SET legacy_article_id = article_id
WHERE legacy_article_id IS NULL;

-- 归属回填：优先单篇认领人，其次学科认领人，最后初始老师
UPDATE public.courseware_catalog AS c
SET teacher_account_id = COALESCE(
        (SELECT MIN(cl.admin_account_id)
           FROM public.admin_courseware_claim AS cl
          WHERE cl.article_id = c.article_id),
        (SELECT MIN(sc.admin_account_id)
           FROM public.admin_subject_claim AS sc
          WHERE sc.subject = c.subject),
        (SELECT teacher_account_id FROM tmp_initial_teacher)
    )
WHERE c.teacher_account_id IS NULL;

CREATE INDEX IF NOT EXISTS courseware_catalog_teacher_idx
    ON public.courseware_catalog (teacher_account_id, subject);

ALTER TABLE public.article_answer_keys
    ADD COLUMN IF NOT EXISTS teacher_account_id bigint,
    ADD COLUMN IF NOT EXISTS release_id bigint;

UPDATE public.article_answer_keys AS k
SET teacher_account_id = c.teacher_account_id
FROM public.courseware_catalog AS c
WHERE k.teacher_account_id IS NULL
  AND c.article_id = k.blog_id;

ALTER TABLE public.article_question_submissions
    ADD COLUMN IF NOT EXISTS teacher_account_id bigint,
    ADD COLUMN IF NOT EXISTS release_id bigint,
    ADD COLUMN IF NOT EXISTS stem_snapshot text,
    ADD COLUMN IF NOT EXISTS answer_snapshot text;

UPDATE public.article_question_submissions AS s
SET teacher_account_id = c.teacher_account_id
FROM public.courseware_catalog AS c
WHERE s.teacher_account_id IS NULL
  AND c.article_id = s.blog_id;

ALTER TABLE public.wrong_questions
    ADD COLUMN IF NOT EXISTS teacher_account_id bigint,
    ADD COLUMN IF NOT EXISTS release_id bigint,
    ADD COLUMN IF NOT EXISTS stem_snapshot text,
    ADD COLUMN IF NOT EXISTS subject text;

UPDATE public.wrong_questions AS w
SET teacher_account_id = c.teacher_account_id,
    subject = COALESCE(w.subject, c.subject)
FROM public.courseware_catalog AS c
WHERE w.teacher_account_id IS NULL
  AND c.article_id = w.source_blog_id;

CREATE INDEX IF NOT EXISTS article_answer_keys_teacher_idx
    ON public.article_answer_keys (teacher_account_id, blog_id, question_id);
CREATE INDEX IF NOT EXISTS article_question_submissions_teacher_idx
    ON public.article_question_submissions (teacher_account_id, blog_id);
CREATE INDEX IF NOT EXISTS wrong_questions_teacher_idx
    ON public.wrong_questions (teacher_account_id, student_id);

